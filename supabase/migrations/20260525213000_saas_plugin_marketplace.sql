-- Indobase plugin marketplace registry.
-- Adds publisher-managed plugin listings, versions, installs, reviews, and categories.

create table if not exists saas.plugin_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text null,
  inserted_at timestamptz not null default now()
);

