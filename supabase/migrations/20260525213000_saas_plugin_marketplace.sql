create table if not exists saas.plugin_listings (
  id uuid primary key default gen_random_uuid(),
  organization_id integer not null references saas.organizations(id) on delete cascade,
  oauth_app_id text null,
  oauth_app_client_id text null,
  oauth_authorize_url text null,
  oauth_redirect_uri text null,
  slug text not null unique,
  name text not null,
  summary text not null default '',
  description_md text not null default '',
  website text null,
  repo_url text null,
  package_type text not null check (package_type in ('cursor_plugin', 'mcp_server')),
  source_type text not null check (source_type in ('github_repo', 'manifest_url', 'mcp_endpoint')),
  visibility text not null default 'draft' check (visibility in ('draft', 'public', 'unlisted', 'archived')),
  review_status text not null default 'draft'
    check (review_status in ('draft', 'submitted', 'approved', 'rejected', 'changes_requested')),
  pricing_model text not null default 'free' check (pricing_model in ('free', 'paid', 'contact')),
  logo_url text null,
  tags text[] not null default '{}'::text[],
  supported_clients text[] not null default '{}'::text[],
  supported_runtimes text[] not null default '{}'::text[],
  install_type text not null default 'mcp' check (install_type in ('mcp', 'plugin_repo', 'hybrid')),
  default_mcp_url text null,
  default_mcp_server_name text not null default 'plugin',
  source_metadata jsonb not null default '{}'::jsonb,
  latest_version_id uuid null,
  published_version_id uuid null,
  latest_validation_status text not null default 'pending'
    check (latest_validation_status in ('pending', 'valid', 'invalid')),
  published_at timestamptz null,
  inserted_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists saas.plugin_versions (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references saas.plugin_listings(id) on delete cascade,
  version text not null,
  changelog text null,
  source_ref text null,
  manifest_path text not null default '.cursor-plugin/plugin.json',
  readme_path text not null default 'README.md',
  mcp_path text null default '.mcp.json',
  package_metadata jsonb not null default '{}'::jsonb,
  manifest_json jsonb null,
  package_files jsonb not null default '[]'::jsonb,
  validation_status text not null default 'pending'
    check (validation_status in ('pending', 'valid', 'invalid')),
  validation_errors jsonb not null default '[]'::jsonb,
  validation_warnings jsonb not null default '[]'::jsonb,
  review_status text not null default 'draft'
    check (review_status in ('draft', 'submitted', 'approved', 'rejected', 'changes_requested')),
  reviewed_by_gotrue_id uuid null,
  reviewed_at timestamptz null,
  inserted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (listing_id, version)
);

create table if not exists saas.plugin_assets (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references saas.plugin_listings(id) on delete cascade,
  version_id uuid null references saas.plugin_versions(id) on delete set null,
  asset_type text not null check (asset_type in ('logo', 'screenshot', 'archive', 'manifest', 'readme')),
  url text not null,
  metadata jsonb not null default '{}'::jsonb,
  inserted_at timestamptz not null default now()
);

create table if not exists saas.plugin_installs (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references saas.plugin_listings(id) on delete cascade,
  version_id uuid null references saas.plugin_versions(id) on delete set null,
  organization_id integer null references saas.organizations(id) on delete set null,
  project_ref text null references saas.projects(ref) on delete set null,
  installed_by_gotrue_id uuid null,
  client text not null,
  install_status text not null default 'requested'
    check (install_status in ('requested', 'authorized', 'installed', 'failed', 'revoked')),
  install_payload jsonb not null default '{}'::jsonb,
  authorization_url text null,
  authorization_completed_at timestamptz null,
  installed_at timestamptz null,
  inserted_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists saas.plugin_reviews (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references saas.plugin_listings(id) on delete cascade,
  version_id uuid null references saas.plugin_versions(id) on delete set null,
  reviewer_gotrue_id uuid null,
  status text not null check (status in ('submitted', 'approved', 'rejected', 'changes_requested')),
  notes text null,
  metadata jsonb not null default '{}'::jsonb,
  inserted_at timestamptz not null default now()
);

create table if not exists saas.plugin_listing_categories (
  listing_id uuid not null references saas.plugin_listings(id) on delete cascade,
  category_id bigint not null references saas.plugin_categories(id) on delete cascade,
  primary key (listing_id, category_id)
);

