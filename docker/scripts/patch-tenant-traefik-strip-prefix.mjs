#!/usr/bin/env node
/**
 * Patch existing tenant-*.yml Traefik dynamic configs to add stripPrefix middlewares
 * (Kong parity). Reads ports/upstream from the current file; safe to re-run.
 *
 * Usage: node docker/scripts/patch-tenant-traefik-strip-prefix.mjs [/path/to/traefik/dynamic]
 */
import fs from 'node:fs'
import path from 'node:path'

const dir = process.argv[2] || '/etc/dokploy/traefik/dynamic'

function parseExisting(content, ref) {
  const upstreamMatch = content.match(/url: "http:\/\/([^:]+):(\d+)"/)
  const upstream = upstreamMatch?.[1] || '172.17.0.1'
  const port = (name) => {
    // Match only the `services:` block (routers also contain `tenant-*-auth:` names).
    const re = new RegExp(
      `tenant-${ref}-${name}:\\s*\\n\\s*loadBalancer:\\s*\\n\\s*servers: \\[{ url: "http://${upstream.replace(/\\./g, '\\.')}:(\\d+)"`,
      'm'
    )
    const m = content.match(re)
    return m ? Number(m[1]) : null
  }
  const hostMatch = content.match(/Host\(`([^`]+)`\)/)
  const hostRule = hostMatch?.[1] || `${ref}.indobase.in`
  return {
    upstream,
    hostRule,
    ports: {
      rest: port('rest'),
      auth: port('auth'),
      storage: port('storage'),
      realtime: port('realtime'),
      functions: port('functions'),
    },
  }
}

function buildYaml(ref, hostRule, upstream, ports) {
  const strip = (name, prefix) => `    tenant-${ref}-${name}-strip:
      stripPrefix:
        prefixes:
          - "${prefix}"
`
  return `# Generated by Studio — per-project routing (REST, Auth, Storage, Realtime, Functions)
http:
  middlewares:
${strip('rest', '/rest/v1')}${strip('auth', '/auth/v1')}${strip('storage', '/storage/v1')}${strip('realtime', '/realtime/v1')}${strip('functions', '/functions/v1')}
  routers:
    tenant-${ref}-rest:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/rest/v1\`)
      middlewares:
        - tenant-${ref}-rest-strip
      service: tenant-${ref}-rest
      entryPoints: [web, websecure]
    tenant-${ref}-auth:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/auth/v1\`)
      middlewares:
        - tenant-${ref}-auth-strip
      service: tenant-${ref}-auth
      entryPoints: [web, websecure]
    tenant-${ref}-storage:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/storage/v1\`)
      middlewares:
        - tenant-${ref}-storage-strip
      service: tenant-${ref}-storage
      entryPoints: [web, websecure]
    tenant-${ref}-realtime:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/realtime/v1\`)
      middlewares:
        - tenant-${ref}-realtime-strip
      service: tenant-${ref}-realtime
      entryPoints: [web, websecure]
    tenant-${ref}-functions:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/functions/v1\`)
      middlewares:
        - tenant-${ref}-functions-strip
      service: tenant-${ref}-functions
      entryPoints: [web, websecure]

  services:
    tenant-${ref}-rest:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.rest}" }]
        passHostHeader: true
    tenant-${ref}-auth:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.auth}" }]
        passHostHeader: true
    tenant-${ref}-storage:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.storage}" }]
        passHostHeader: true
    tenant-${ref}-realtime:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.realtime}" }]
        passHostHeader: true
    tenant-${ref}-functions:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.functions}" }]
        passHostHeader: true
`
}

const files = fs.readdirSync(dir).filter((f) => f.startsWith('tenant-') && f.endsWith('.yml'))
let patched = 0
for (const file of files) {
  const ref = file.slice('tenant-'.length, -'.yml'.length)
  const filePath = path.join(dir, file)
  const content = fs.readFileSync(filePath, 'utf8')
  const force = process.argv.includes('--force')
  if (!force && content.includes('-rest-strip') && content.includes('loadBalancer')) {
    const authSvc = content.match(
      new RegExp(`tenant-${ref}-auth:\\s*\\n\\s*loadBalancer:[\\s\\S]*?url: "http://[^"]+:(\\d+)"`)
    )
    const restSvc = content.match(
      new RegExp(`tenant-${ref}-rest:\\s*\\n\\s*loadBalancer:[\\s\\S]*?url: "http://[^"]+:(\\d+)"`)
    )
    if (authSvc && restSvc && authSvc[1] !== restSvc[1]) {
      continue
    }
  }
  const { upstream, hostRule, ports } = parseExisting(content, ref)
  if (Object.values(ports).some((p) => p == null)) {
    console.warn(`skip ${file}: could not parse all ports`, ports)
    continue
  }
  fs.writeFileSync(filePath, buildYaml(ref, hostRule, upstream, ports), 'utf8')
  patched++
  console.log(`patched ${file}`)
}
console.log(`done: ${patched} file(s) updated in ${dir}`)
