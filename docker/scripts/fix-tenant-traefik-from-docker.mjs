#!/usr/bin/env node
/**
 * Rewrite tenant-*.yml using live host ports from `docker ps` (authoritative after bad patches).
 * Usage: node docker/scripts/fix-tenant-traefik-from-docker.mjs [/path/to/traefik/dynamic]
 */
const fs = require('node:fs')
const path = require('node:path')
const { execSync } = require('node:child_process')

const dir = process.argv[2] || '/etc/dokploy/traefik/dynamic'
const upstream = process.env.TRAEFIK_UPSTREAM_HOST?.trim() || '172.17.0.1'
const domain = process.env.PUBLIC_DOMAIN?.trim() || 'indobase.in'

const dockerPs = execSync('docker ps --format "{{.Names}}\t{{.Ports}}"', { encoding: 'utf8' })

function hostPortFor(ref, svc) {
  const needles =
    svc === 'realtime'
      ? [`${ref}.indobase-realtime`, `${ref}-tenant-realtime`]
      : [`${ref}-tenant-${svc}`]
  const line = dockerPs.split('\n').find((l) => needles.some((n) => l.includes(n)))
  if (!line) return null
  const m = line.match(/0\.0\.0\.0:(\d+)->/)
  return m ? Number(m[1]) : null
}

function buildYaml(ref, hostRule, ports) {
  const strip = (name, prefix) => `    tenant-${ref}-${name}-strip:
      stripPrefix:
        prefixes:
          - "${prefix}"
`
  return `# Generated by Studio — per-project routing (REST, Auth, Storage, Realtime, Functions)
http:
  middlewares:
${strip('rest', '/rest/v1')}${strip('auth', '/auth/v1')}${strip('storage', '/storage/v1')}${strip('realtime', '/realtime/v1')}${strip('functions', '/functions/v1')}
  routers:
    tenant-${ref}-rest:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/rest/v1\`)
      middlewares:
        - tenant-${ref}-rest-strip
      service: tenant-${ref}-rest
      entryPoints: [web, websecure]
    tenant-${ref}-auth:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/auth/v1\`)
      middlewares:
        - tenant-${ref}-auth-strip
      service: tenant-${ref}-auth
      entryPoints: [web, websecure]
    tenant-${ref}-storage:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/storage/v1\`)
      middlewares:
        - tenant-${ref}-storage-strip
      service: tenant-${ref}-storage
      entryPoints: [web, websecure]
    tenant-${ref}-realtime:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/realtime/v1\`)
      middlewares:
        - tenant-${ref}-realtime-strip
      service: tenant-${ref}-realtime
      entryPoints: [web, websecure]
    tenant-${ref}-functions:
      rule: Host(\`${hostRule}\`) && PathPrefix(\`/functions/v1\`)
      middlewares:
        - tenant-${ref}-functions-strip
      service: tenant-${ref}-functions
      entryPoints: [web, websecure]

  services:
    tenant-${ref}-rest:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.rest}" }]
        passHostHeader: true
    tenant-${ref}-auth:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.auth}" }]
        passHostHeader: true
    tenant-${ref}-storage:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.storage}" }]
        passHostHeader: true
    tenant-${ref}-realtime:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.realtime}" }]
        passHostHeader: true
    tenant-${ref}-functions:
      loadBalancer:
        servers: [{ url: "http://${upstream}:${ports.functions}" }]
        passHostHeader: true
`
}

let fixed = 0
for (const file of fs.readdirSync(dir).filter((f) => f.startsWith('tenant-') && f.endsWith('.yml'))) {
  const ref = file.slice('tenant-'.length, -'.yml'.length)
  const ports = {
    rest: hostPortFor(ref, 'rest'),
    auth: hostPortFor(ref, 'auth'),
    storage: hostPortFor(ref, 'storage'),
    realtime: hostPortFor(ref, 'realtime'),
    functions: hostPortFor(ref, 'functions'),
  }
  if (Object.values(ports).some((p) => !p)) {
    console.warn('skip', file, ports)
    continue
  }
  fs.writeFileSync(path.join(dir, file), buildYaml(ref, `${ref}.${domain}`, ports), 'utf8')
  console.log('fixed', file, ports)
  fixed++
}
console.log(`done: ${fixed} file(s) in ${dir}`)
